        /// <summary>
        /// The text for <paramref name="key"/> in <paramref name="language"/>; falls back to English, then to the key itself,
        /// so a missing translation shows readable text rather than nothing.
        /// </summary>
        public static string Get(string language, string key)
        {
            if (Table.TryGetValue(language, out var dictionary) && dictionary.TryGetValue(key, out var value))
                return value;
            return Table["en"].TryGetValue(key, out var english) ? english : key;
        }

        /// <summary>True when <paramref name="key"/> has text in <paramref name="language"/> itself (no fallback).</summary>
        public static bool Has(string language, string key) =>
            Table.TryGetValue(language, out var dictionary) && dictionary.ContainsKey(key);
